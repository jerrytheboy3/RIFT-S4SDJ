import sys, pathlib
from playwright.sync_api import sync_playwright
URL = pathlib.Path(sys.argv[1]).as_uri() + "?now=2026-10-22T10:05:00%2B05:30"
FX = pathlib.Path("test/fixtures").resolve()
ok = fail = 0
def check(name, cond, extra=""):
    global ok, fail
    if cond: ok += 1
    else: fail += 1; print("FAIL", name, extra)
with sync_playwright() as p:
    b = p.chromium.launch(channel="chrome", headless=True)
    ctx = b.new_context(viewport={"width":1440,"height":900}); ctx.grant_permissions(["clipboard-read", "clipboard-write"])
    pg = ctx.new_page(); errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
    pg.goto(URL + "#documents"); pg.wait_for_timeout(1200)
    check("vault opens", pg.locator(".vgrid .vcard").count() >= 8, str(pg.locator(".vgrid .vcard").count()))
    check("idb ok", pg.evaluate("Vault.ok"))
    pg.screenshot(path="shots9/v_empty.png")
    pg.click('.vcard [data-type="aadhaar"].vadd'); pg.wait_for_timeout(500)
    pg.fill("#ve-num", "12341234"); pg.wait_for_timeout(100)
    check("soft warning", "does not look like" in pg.inner_text("#ve-hint"))
    pg.fill("#ve-num", "1234 5678 9012"); pg.wait_for_timeout(100)
    check("warning clears", "does not look" not in pg.inner_text("#ve-hint"))
    pg.fill("#ve-notes", "Original in the blue folder")
    pg.set_input_files("#ve-file", [str(FX / "aadhaar-front.png"), str(FX / "scan.pdf")]); pg.wait_for_timeout(300)
    check("draft files", pg.locator("#ve-files li").count() == 2)
    pg.screenshot(path="shots9/v_editor.png")
    pg.click('.vedit-form button[type="submit"]'); pg.wait_for_timeout(1200)
    card = pg.locator(".vcard.has").first
    check("masked", "XXXX XXXX 9012" in card.inner_text(), card.inner_text()[:120])
    check("thumbs", pg.evaluate("[...document.querySelectorAll('img[data-vthumb]')].every(i => i.src.startsWith('blob:'))") and pg.locator(".vfile").count() == 2)
    check("doc ticked", pg.evaluate("S.docs.aadhaar === true"))
    pg.screenshot(path="shots9/v_saved.png")
    pg.click('[data-vact="reveal"]'); pg.wait_for_timeout(300)
    check("reveal", "1234 5678 9012" in pg.inner_text(".vnum-v"))
    pg.click('[data-vact="copy"]'); pg.wait_for_timeout(300)
    check("copy", pg.evaluate("navigator.clipboard.readText()") == "1234 5678 9012")
    pg.reload(); pg.wait_for_timeout(1500)
    check("persists", "XXXX XXXX 9012" in pg.inner_text(".vgrid"))
    # passcode
    pg.click('[data-vact="setpass"]'); pg.wait_for_timeout(400)
    pg.fill("#vp-1", "2468"); pg.fill("#vp-2", "2469"); pg.click('[data-vform="setpass"] button[type="submit"]'); pg.wait_for_timeout(200)
    check("mismatch", "do not match" in pg.inner_text("#vp-err"))
    pg.fill("#vp-2", "2468"); pg.click('[data-vform="setpass"] button[type="submit"]'); pg.wait_for_timeout(2500)
    raw = pg.evaluate("(async () => { const r = await Vault.get('meta','state'); return JSON.stringify(r).includes('1234 5678'); })()")
    check("encrypted at rest", raw is False)
    pg.reload(); pg.wait_for_timeout(1500)
    check("locked after reload", pg.locator("#v-pass").count() == 1)
    pg.screenshot(path="shots9/v_locked.png")
    pg.fill("#v-pass", "1111"); pg.click('.vault-unlock button'); pg.wait_for_timeout(1500)
    check("wrong pass", "did not match" in pg.inner_text("#v-err"))
    pg.fill("#v-pass", "2468"); pg.click('.vault-unlock button'); pg.wait_for_timeout(1800)
    check("unlocked", "XXXX XXXX 9012" in pg.inner_text(".vgrid"))
    check("thumb decrypts", pg.evaluate("[...document.querySelectorAll('img[data-vthumb]')].every(i => i.src.startsWith('blob:'))"))
    pg.click('[data-vact="nopass"]'); pg.wait_for_timeout(300); pg.click("#vc-yes"); pg.wait_for_timeout(2000)
    pg.reload(); pg.wait_for_timeout(1500)
    check("passcode removed", pg.locator("#v-pass").count() == 0 and "XXXX XXXX 9012" in pg.inner_text(".vgrid"))
    # clear all data needs confirmation
    pg.goto(URL + "#settings"); pg.wait_for_timeout(900)
    pg.click("#clear-all"); pg.wait_for_timeout(500)
    check("confirm dialog", pg.locator("#cc-h").count() == 1)
    pg.screenshot(path="shots9/v_confirm.png")
    pg.click("#cc-cancel"); pg.wait_for_timeout(400)
    check("cancel keeps data", pg.evaluate("S.docs.aadhaar === true"))
    pg.click("#clear-all"); pg.wait_for_timeout(400); pg.click("#cc-yes"); pg.wait_for_timeout(1500)
    check("cleared", pg.evaluate("!S.docs.aadhaar") and pg.evaluate("Vault.items.length === 0"))
    pg.goto(URL + "#documents"); pg.wait_for_timeout(1200)
    check("vault empty after clear", pg.locator(".vcard.has").count() == 0)
    pg.goto(URL + "#about"); pg.wait_for_timeout(1200)
    pg.evaluate("document.getElementById('sdg-h').scrollIntoView()"); pg.wait_for_timeout(1500)
    pg.screenshot(path="shots9/sdg1.png")
    pg.mouse.wheel(0, 800); pg.wait_for_timeout(1600); pg.screenshot(path="shots9/sdg2.png")
    print("errors:", errs)
    print(f"{ok}/{ok+fail} passed")
    b.close()
